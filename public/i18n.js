// Resolver function to map any dialect name, localized name, or ISO code to registered language key
function resolveLangKey(str) {
  if (!str) return 'en';
  const s = String(str).toLowerCase().trim();
  if (CYPHER_I18N[s]) return s;
  if (s.includes('hindi') || s.includes('हिन्दी') || s === 'hi') return 'hi';
  if (s.includes('telugu') || s.includes('తెలుగు') || s === 'te') return 'te';
  if (s.includes('tamil') || s.includes('தமிழ்') || s === 'ta') return 'ta';
  if (s.includes('bengali') || s.includes('বাংলা') || s === 'bn') return 'bn';
  if (s.includes('marathi') || s.includes('मराठी') || s === 'mr') return 'mr';
  if (s.includes('russian') || s.includes('русский') || s === 'ru') return 'ru';
  if (s.includes('mandarin') || s.includes('普通话') || s.includes('chinese') || s.includes('中文') || s === 'zh') return 'zh';
  if (s.includes('cantonese') || s.includes('yue') || s.includes('粤语') || s === 'yue') return 'yue';
  if (s.includes('shanghainese') || s.includes('sichuanese') || s.includes('hakka')) return 'zh';
  if (s.includes('portug') || s.includes('brasil') || s === 'pt') return 'pt';
  if (s.includes('arabic') || s.includes('العربية') || s.includes('gulf') || s.includes('najdi') || s.includes('egyptian') || s === 'ar') return 'ar';
  if (s.includes('persian') || s.includes('farsi') || s.includes('فارسی') || s.includes('azerbaijani') || s === 'fa') return 'fa';
  if (s.includes('amharic') || s.includes('አማርኛ') || s.includes('oromo') || s.includes('tigrinya') || s === 'am') return 'am';
  if (s.includes('zulu') || s.includes('isizulu') || s === 'zu') return 'zu';
  if (s.includes('xhosa') || s.includes('isixhosa') || s === 'xh') return 'xh';
  if (s.includes('afrikaans') || s === 'af') return 'af';
  if (s.includes('german') || s.includes('deutsch') || s === 'de') return 'de';
  if (s.includes('italian') || s.includes('italiano') || s === 'it') return 'it';
  if (s.includes('tatar') || s.includes('татар') || s === 'tt') return 'tt';
  if (s.includes('chechen') || s.includes('нохчийн') || s === 'ce') return 'ce';
  if (s.includes('bashkir') || s.includes('башҡорт') || s === 'ba') return 'ba';
  if (s.includes('tikuna') || s.includes('ticuna') || s === 'tco') return 'tco';
  return 'en';
}

// Comprehensive helper to match any selected dialect or language string
function getSavedLanguage() {
  try {
    // 1. Check URL query parameters (?lang=...)
    const urlParams = new URLSearchParams(window.location.search);
    const paramLang = urlParams.get('lang') || urlParams.get('language');
    if (paramLang) {
      const resolved = resolveLangKey(paramLang);
      if (resolved) return resolved;
    }

    // 2. Check stored session
    const raw = sessionStorage.getItem('brics_citizen_session') || localStorage.getItem('brics_citizen_session');
    if (raw) {
      const session = JSON.parse(raw);
      if (session.language) {
        return resolveLangKey(session.language);
      }
    }

    // 3. Check simple key
    const direct = sessionStorage.getItem('brics_active_lang') || localStorage.getItem('brics_active_lang');
    if (direct) {
      return resolveLangKey(direct);
    }
  } catch (e) {}
  return 'en';
}

// Apply translations dynamically across the DOM with fallback to English
function applyCypherTranslations(targetLangKey = null) {
  let langKey = targetLangKey ? resolveLangKey(targetLangKey) : getSavedLanguage();
  if (!langKey || !CYPHER_I18N[langKey]) {
    langKey = 'en';
  }

  const dict = CYPHER_I18N[langKey];
  const fallback = CYPHER_I18N['en'];

  // 1. Text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = dict[key] || fallback[key];
    if (val !== undefined && val !== null) {
      el.textContent = val;
    }
  });

  // 2. Placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = dict[key] || fallback[key];
    if (val) {
      el.setAttribute('placeholder', val);
    }
  });

  // 3. Dropdown option elements with data-i18n-option
  document.querySelectorAll('option[data-i18n-option]').forEach(opt => {
    const key = opt.getAttribute('data-i18n-option');
    const val = dict[key] || fallback[key];
    if (val) {
      opt.textContent = val;
    }
  });

  // 4. Update language header selector if present
  const langSelect = document.getElementById('cypher-lang-selector') || document.getElementById('admin-lang-selector');
  if (langSelect) {
    langSelect.value = langKey;
  }

  // 5. Update header language label
  const headerLangLabel = document.getElementById('header-lang-name');
  if (headerLangLabel && dict.langName) {
    headerLangLabel.textContent = dict.langName.split(' ')[0];
  }

  // 6. Set HTML lang and directional attribute for RTL languages (Arabic, Persian)
  document.documentElement.lang = langKey;
  if (langKey === 'ar' || langKey === 'fa') {
    document.documentElement.setAttribute('dir', 'rtl');
  } else {
    document.documentElement.setAttribute('dir', 'ltr');
  }

  // 7. Dispatch event for canvas or spatial elements to update
  try {
    window.dispatchEvent(new CustomEvent('cypher:languageChanged', {
      detail: { langKey, dict }
    }));
  } catch (e) {}

  return langKey;
}

// Switch language dynamically and persist to citizen session
function switchCypherLanguage(newLangInput) {
  const newLangKey = resolveLangKey(newLangInput);
  try {
    let session = {};
    const saved = sessionStorage.getItem('brics_citizen_session') || localStorage.getItem('brics_citizen_session');
    if (saved) {
      session = JSON.parse(saved);
    }
    const dict = CYPHER_I18N[newLangKey] || CYPHER_I18N['en'];
    session.language = dict.langName || newLangKey;
    sessionStorage.setItem('brics_citizen_session', JSON.stringify(session));
    localStorage.setItem('brics_citizen_session', JSON.stringify(session));
    sessionStorage.setItem('brics_active_lang', newLangKey);
    localStorage.setItem('brics_active_lang', newLangKey);
  } catch (e) {}

  applyCypherTranslations(newLangKey);

  // If 3D cards updater is registered, refresh textures in Three.js
  if (typeof window.updateAllCardTextures === 'function') {
    window.updateAllCardTextures(newLangKey);
  }

  return newLangKey;
}

// Expose on window for global access
window.CYPHER_I18N = CYPHER_I18N;
window.CYPHER_BASE_EN = CYPHER_BASE_EN;
window.resolveLangKey = resolveLangKey;
window.getSavedLanguage = getSavedLanguage;
window.applyCypherTranslations = applyCypherTranslations;
window.switchCypherLanguage = switchCypherLanguage;
